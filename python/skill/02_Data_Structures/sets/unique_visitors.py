visitors = ["fahim", "rahim", "karim", "fahim", "rahim", "sadia"]

unique_visitors = set(visitors)

def len_unique_visitors():
    return len(unique_visitors)
print(len_unique_visitors())  # Output: 4

def list_of_unique_visitors():
    return unique_visitors
print(list_of_unique_visitors())  # Output: {'fahim', 'rahim', 'karim', 'sadia'}

